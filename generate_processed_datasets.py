import os
import cv2
import time
import pandas as pd
import config
from utils import CustomMRIDataset
from ml_core.preprocess_fft_clahe import apply_fft_clahe

def generate_datasets():
    dataset = CustomMRIDataset(config.DATASET_ROOT)
    
    timing_data = []
    
    for level, ratio in config.COMPRESSION_RATIOS.items():
        print(f"Generating compressed dataset: {level} (ratio={ratio})")
        level_dir = os.path.join(config.PROCESSED_DATASETS_DIR, level)
        os.makedirs(os.path.join(level_dir, "yes"), exist_ok=True)
        os.makedirs(os.path.join(level_dir, "no"), exist_ok=True)
        
        for img_path, label in dataset.samples:
            class_name = "yes" if label == 1 else "no"
            # Change output extension to .jpg to actually compress the file size
            filename, _ = os.path.splitext(os.path.basename(img_path))
            out_path = os.path.join(level_dir, class_name, f"{filename}.jpg")
            
            # Read Grayscale
            img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
            
            # Find true background to mask out noise generated by FFT -> CLAHE
            _, bg_mask = cv2.threshold(img, 3, 255, cv2.THRESH_BINARY)
            bg_mask = (bg_mask / 255).astype(img.dtype)
            
            start_time = time.perf_counter()
            processed_img = apply_fft_clahe(img, ratio, config.CLAHE_CLIP_LIMIT, config.CLAHE_TILE_GRID)
            # Zero out background immediately after to eliminate noise inflation
            processed_img = processed_img * bg_mask
            # Replicate channels to preserve 3-channel structure
            processed_img_3c = cv2.cvtColor(processed_img, cv2.COLOR_GRAY2BGR)
            fft_clahe_time_ms = (time.perf_counter() - start_time) * 1000
            
            # Determine lower variable JPEG quality to force aggressive size reduction
            quality_map = {"light": 75, "intermediate": 45, "aggressive": 15}
            jpeg_quality = quality_map.get(level, 85)
            
            # Save as JPEG dynamically lowering quality
            cv2.imwrite(out_path, processed_img_3c, [cv2.IMWRITE_JPEG_QUALITY, jpeg_quality])
            
            timing_data.append({
                "compression_level": level,
                "original_image_path": img_path,
                "processed_image_path": out_path,
                "fft_clahe_processing_time_ms": fft_clahe_time_ms
            })
            
    df = pd.DataFrame(timing_data)
    df.to_csv(os.path.join(config.RESULTS_DIR, "generation_times.csv"), index=False)
    print("Dataset generation complete. Timing saved.")

if __name__ == "__main__":
    generate_datasets()
